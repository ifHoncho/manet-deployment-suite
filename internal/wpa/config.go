// Package wpa renders wpa_supplicant configuration for an 802.11s mesh with
// SAE and speaks the wpa_supplicant control-interface protocol.
package wpa

import (
	"encoding/hex"
	"fmt"
	"strings"
)

// MeshConfig is everything needed for one mesh interface.
type MeshConfig struct {
	CtrlDir    string
	MeshID     string
	Passphrase string
	FreqMHz    int
	WidthMHz   int // 20, 40 or 80
	// MeshFwding enables 802.11s layer-2 forwarding. Trellis keeps it off:
	// batman-adv owns all paths (architecture §5).
	MeshFwding bool
	// Optional tuning. Zero values leave wpa_supplicant's defaults.
	BeaconIntTU   int
	BasicRates    []int // in 100 kbit/s units, e.g. 60 120 240
	RSSIThreshold *int  // dBm; peers below are not connected (0 disables)
	MaxPeerLinks  int
}

// 80 MHz block centre channels in the 5 GHz band.
var centre80 = []int{42, 58, 106, 122, 138, 155, 171}

// CenterFreq80 returns the centre frequency of the 80 MHz block containing
// a 5 GHz primary channel frequency, or 0 if none.
func CenterFreq80(freqMHz int) int {
	for _, c := range centre80 {
		centre := 5000 + 5*c
		if freqMHz >= centre-40 && freqMHz < centre+40 {
			return centre
		}
	}
	return 0
}

// Render produces the wpa_supplicant configuration file contents.
func Render(c MeshConfig) string {
	var b strings.Builder
	b.WriteString("# Generated by trellis meshd. Changes are overwritten.\n")
	fmt.Fprintf(&b, "ctrl_interface=DIR=%s\n", c.CtrlDir)
	b.WriteString("update_config=0\n")
	b.WriteString("p2p_disabled=1\n")
	if c.MaxPeerLinks > 0 {
		fmt.Fprintf(&b, "max_peer_links=%d\n", c.MaxPeerLinks)
	}
	b.WriteString("\nnetwork={\n")
	// Hex form avoids every quoting question for the mesh ID.
	fmt.Fprintf(&b, "\tssid=%s\n", hex.EncodeToString([]byte(c.MeshID)))
	b.WriteString("\tmode=5\n")
	fmt.Fprintf(&b, "\tfrequency=%d\n", c.FreqMHz)
	b.WriteString("\tkey_mgmt=SAE\n")
	fmt.Fprintf(&b, "\tsae_password=\"%s\"\n", c.Passphrase)
	b.WriteString("\tieee80211w=2\n")
	if c.MeshFwding {
		b.WriteString("\tmesh_fwding=1\n")
	} else {
		b.WriteString("\tmesh_fwding=0\n")
	}
	switch c.WidthMHz {
	case 40:
		b.WriteString("\tht40=1\n")
	case 80:
		b.WriteString("\tht40=1\n")
		b.WriteString("\tvht=1\n")
		b.WriteString("\tmax_oper_chwidth=1\n")
		if cf := CenterFreq80(c.FreqMHz); cf != 0 {
			fmt.Fprintf(&b, "\tvht_center_freq1=%d\n", cf)
		}
	default:
		b.WriteString("\tdisable_ht40=1\n")
	}
	if c.BeaconIntTU > 0 {
		fmt.Fprintf(&b, "\tbeacon_int=%d\n", c.BeaconIntTU)
	}
	if len(c.BasicRates) > 0 {
		parts := make([]string, len(c.BasicRates))
		for i, r := range c.BasicRates {
			parts[i] = fmt.Sprint(r)
		}
		fmt.Fprintf(&b, "\tmesh_basic_rates=%s\n", strings.Join(parts, " "))
	}
	if c.RSSIThreshold != nil {
		fmt.Fprintf(&b, "\tmesh_rssi_threshold=%d\n", *c.RSSIThreshold)
	}
	b.WriteString("}\n")
	return b.String()
}

// PassphraseOK reports whether a passphrase can be written into a quoted
// wpa_supplicant string without escaping: printable ASCII, no quotes or
// backslashes.
func PassphraseOK(s string) error {
	for i, r := range s {
		if r < 0x20 || r > 0x7e {
			return fmt.Errorf("character %d is not printable ASCII", i+1)
		}
		if r == '"' || r == '\\' {
			return fmt.Errorf("character %d (%q) is not allowed", i+1, r)
		}
	}
	return nil
}
