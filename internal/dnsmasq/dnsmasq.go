// Package dnsmasq renders the per-node dnsmasq configuration (DHCP pool and
// .mesh DNS, architecture §7.5–7.6) and reads its lease file.
package dnsmasq

import (
	"bufio"
	"fmt"
	"io"
	"strconv"
	"strings"
	"time"
)

// Config is one node's dnsmasq setup.
type Config struct {
	Interfaces       []string // listen for DNS and DHCP
	NoDHCPInterfaces []string // listen for DNS only
	Domain           string   // mesh
	PoolStart        string
	PoolEnd          string
	Netmask          string
	LeaseTime        string // dnsmasq syntax, e.g. 24h
	Router           string // anycast gateway
	DNS              string // anycast gateway
	LeaseFile        string
	LeaseMax         int
	HostRecords      []HostRecord
	// Upstream resolvers for names outside the mesh (M3: the selected
	// gateway). Empty: such names fail at once instead of timing out.
	Upstream []string
	// ServersFile and HostsFile are re-read on SIGHUP, so upstreams and
	// other nodes' names change without a restart (or a lost cache).
	ServersFile string
	HostsFile   string
}

// ServersFileContent renders upstream resolvers for --servers-file.
func ServersFileContent(upstream []string) string {
	var b strings.Builder
	b.WriteString("# Generated by trellis meshd: the selected gateway's resolver.\n")
	for _, u := range upstream {
		fmt.Fprintf(&b, "server=%s\n", u)
	}
	return b.String()
}

// HostsFileContent renders .mesh names for --addn-hosts.
func HostsFileContent(domain string, hosts []HostRecord) string {
	var b strings.Builder
	b.WriteString("# Generated by trellis meshd from gossip: other nodes' names.\n")
	for _, h := range hosts {
		fmt.Fprintf(&b, "%s %s.%s %s\n", h.IP, h.Name, domain, h.Name)
	}
	return b.String()
}

// HostRecord is a static .mesh name.
type HostRecord struct {
	Name string // without the domain
	IP   string
}

// Render produces the configuration file contents.
func Render(c Config) string {
	var b strings.Builder
	b.WriteString("# Generated by trellis meshd. Changes are overwritten.\n")
	b.WriteString("bind-dynamic\n")
	for _, i := range c.Interfaces {
		fmt.Fprintf(&b, "interface=%s\n", i)
	}
	for _, i := range c.NoDHCPInterfaces {
		fmt.Fprintf(&b, "interface=%s\nno-dhcp-interface=%s\n", i, i)
	}
	b.WriteString("except-interface=lo\n")
	b.WriteString("no-hosts\n")
	b.WriteString("no-resolv\n")
	b.WriteString("domain-needed\n")
	b.WriteString("bogus-priv\n")
	b.WriteString("cache-size=1000\n")
	fmt.Fprintf(&b, "domain=%s\n", c.Domain)
	fmt.Fprintf(&b, "local=/%s/\n", c.Domain)
	b.WriteString("expand-hosts\n")
	for _, u := range c.Upstream {
		fmt.Fprintf(&b, "server=%s\n", u)
	}
	if c.ServersFile != "" {
		fmt.Fprintf(&b, "servers-file=%s\n", c.ServersFile)
	}
	if c.HostsFile != "" {
		fmt.Fprintf(&b, "addn-hosts=%s\n", c.HostsFile)
	}
	for _, h := range c.HostRecords {
		fmt.Fprintf(&b, "host-record=%s.%s,%s\n", h.Name, c.Domain, h.IP)
	}
	b.WriteString("dhcp-authoritative\n")
	// No ICMP probe of an address before offering it: pools never overlap
	// between nodes, static devices live outside them, and the probe both
	// delays the first lease and leaves a failed neighbour entry for the
	// client on the node, which then delays the node's first reply to it.
	b.WriteString("no-ping\n")
	fmt.Fprintf(&b, "dhcp-range=%s,%s,%s,%s\n", c.PoolStart, c.PoolEnd, c.Netmask, c.LeaseTime)
	fmt.Fprintf(&b, "dhcp-option=option:router,%s\n", c.Router)
	fmt.Fprintf(&b, "dhcp-option=option:dns-server,%s\n", c.DNS)
	fmt.Fprintf(&b, "dhcp-option=option:domain-search,%s\n", c.Domain)
	fmt.Fprintf(&b, "dhcp-leasefile=%s\n", c.LeaseFile)
	if c.LeaseMax > 0 {
		fmt.Fprintf(&b, "dhcp-lease-max=%d\n", c.LeaseMax)
	}
	b.WriteString("dhcp-rapid-commit\n")
	b.WriteString("log-facility=-\n")
	return b.String()
}

// Lease is one line of the lease file.
type Lease struct {
	Expires  time.Time
	MAC      string
	IP       string
	Hostname string // "" when the client sent none
	ClientID string
}

// ParseLeases reads dnsmasq's lease file format:
//
//	<expiry unix time> <mac> <ip> <hostname|*> <client-id|*>
func ParseLeases(r io.Reader) []Lease {
	var out []Lease
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) < 4 {
			continue
		}
		exp, err := strconv.ParseInt(f[0], 10, 64)
		if err != nil {
			continue
		}
		l := Lease{Expires: time.Unix(exp, 0), MAC: f[1], IP: f[2]}
		if f[3] != "*" {
			l.Hostname = f[3]
		}
		if len(f) > 4 && f[4] != "*" {
			l.ClientID = f[4]
		}
		out = append(out, l)
	}
	return out
}
