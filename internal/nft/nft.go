// Package nft renders the bridge-family nftables ruleset that keeps the
// client network local to each node (architecture §7.7) and applies it
// atomically with the nft tool.
package nft

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"os/exec"
	"strings"
)

// Table is the nftables table name, in the bridge family.
const Table = "trellis"

// Ruleset is everything the bat0 and client-port filters depend on.
type Ruleset struct {
	MeshPort    string   // bat0
	ClientPorts []string // ap0 and wired client ports
	AnycastIP   string
	AnycastMAC  string
	// LinkLocalRate caps link-local multicast (mDNS and friends) leaving
	// over the mesh, in frames per second. 0 = 20.
	LinkLocalRate int
	// BroadcastUDPPorts are IPv4 broadcast destination ports still allowed
	// over the mesh. Everything else broadcast is dropped.
	BroadcastUDPPorts []int
	// GossipPort is kept off client ports in both directions: end-user
	// devices neither see nor inject node-to-node control data. 0 = none.
	GossipPort int
}

// Rule names used as comments, so counters can be read back by purpose.
const (
	RuleAnycastARP   = "anycast-arp"
	RuleAnycastMAC   = "anycast-mac"
	RuleDHCPBcast    = "dhcp-broadcast"
	RuleIPv6RA       = "ipv6-ra"
	RuleDHCPv6       = "dhcpv6"
	RuleChatter      = "chatter"
	RuleLinkLocal    = "link-local-multicast"
	RuleIPv4Bcast    = "ipv4-broadcast"
	RuleRogueDHCP    = "rogue-dhcp-server"
	RuleRogueRA      = "rogue-ipv6-ra"
	RuleRogueQuerier = "rogue-multicast-querier"
	RuleIGMP         = "igmp"
	RuleGossip       = "gossip-to-from-clients"
	chainToClient    = "to_clients"
	chainFromMesh    = "from_mesh"
	chainToMesh      = "to_mesh"
	chainFromClient  = "from_clients"
)

// Render produces an nft script that replaces the table atomically: the
// first two lines create-or-delete it so the whole file is one
// transaction whether or not the table exists.
func (r Ruleset) Render() string {
	rate := r.LinkLocalRate
	if rate == 0 {
		rate = 20
	}
	var b strings.Builder
	fmt.Fprintf(&b, "table bridge %s\ndelete table bridge %s\n", Table, Table)
	fmt.Fprintf(&b, "table bridge %s {\n", Table)
	b.WriteString("\t# Generated by trellis meshd. Changes are overwritten.\n")

	anycast := func() {
		fmt.Fprintf(&b, "\t\tarp daddr ip %s counter drop comment %q\n", r.AnycastIP, RuleAnycastARP)
		fmt.Fprintf(&b, "\t\tarp saddr ip %s counter drop comment %q\n", r.AnycastIP, RuleAnycastARP)
		fmt.Fprintf(&b, "\t\tether saddr %s counter drop comment %q\n", r.AnycastMAC, RuleAnycastMAC)
		fmt.Fprintf(&b, "\t\tether daddr %s counter drop comment %q\n", r.AnycastMAC, RuleAnycastMAC)
	}
	both := func() {
		fmt.Fprintf(&b, "\t\tether daddr ff:ff:ff:ff:ff:ff udp dport { 67, 68 } counter drop comment %q\n", RuleDHCPBcast)
		fmt.Fprintf(&b, "\t\ticmpv6 type nd-router-advert counter drop comment %q\n", RuleIPv6RA)
		fmt.Fprintf(&b, "\t\tudp dport { 546, 547 } counter drop comment %q\n", RuleDHCPv6)
	}

	fmt.Fprintf(&b, "\tchain %s {\n", chainFromMesh)
	anycast()
	both()
	b.WriteString("\t}\n")

	fmt.Fprintf(&b, "\tchain %s {\n", chainToMesh)
	anycast()
	both()
	fmt.Fprintf(&b, "\t\tip daddr { 239.255.255.250, 224.0.0.252 } counter drop comment %q\n", RuleChatter)
	fmt.Fprintf(&b, "\t\tether daddr ff:ff:ff:ff:ff:ff udp dport { 137, 138 } counter drop comment %q\n", RuleChatter)
	// IGMP is tiny and carries the listener state multicast depends on:
	// an mDNS burst must never crowd it out of the limit below.
	fmt.Fprintf(&b, "\t\tip protocol igmp accept comment %q\n", RuleIGMP)
	fmt.Fprintf(&b, "\t\tip daddr 224.0.0.0/24 limit rate over %d/second counter drop comment %q\n", rate, RuleLinkLocal)
	if len(r.BroadcastUDPPorts) > 0 {
		ports := make([]string, len(r.BroadcastUDPPorts))
		for i, p := range r.BroadcastUDPPorts {
			ports[i] = fmt.Sprint(p)
		}
		fmt.Fprintf(&b, "\t\tether daddr ff:ff:ff:ff:ff:ff udp dport { %s } accept comment \"allowed-broadcast\"\n", strings.Join(ports, ", "))
	}
	fmt.Fprintf(&b, "\t\tether daddr ff:ff:ff:ff:ff:ff ether type ip counter drop comment %q\n", RuleIPv4Bcast)
	b.WriteString("\t}\n")

	fmt.Fprintf(&b, "\tchain %s {\n", chainFromClient)
	fmt.Fprintf(&b, "\t\tudp sport 67 udp dport 68 counter drop comment %q\n", RuleRogueDHCP)
	fmt.Fprintf(&b, "\t\ticmpv6 type nd-router-advert counter drop comment %q\n", RuleRogueRA)
	// A querier on a client port would win the election or at least shadow
	// the mesh's querier, and batman-adv would then want all multicast.
	fmt.Fprintf(&b, "\t\tigmp type membership-query counter drop comment %q\n", RuleRogueQuerier)
	fmt.Fprintf(&b, "\t\ticmpv6 type mld-listener-query counter drop comment %q\n", RuleRogueQuerier)
	if r.GossipPort != 0 {
		fmt.Fprintf(&b, "\t\tudp dport %d counter drop comment %q\n", r.GossipPort, RuleGossip)
	}
	b.WriteString("\t}\n")
	if r.GossipPort != 0 && len(r.ClientPorts) > 0 {
		fmt.Fprintf(&b, "\tchain %s {\n", chainToClient)
		fmt.Fprintf(&b, "\t\tudp dport %d counter drop comment %q\n", r.GossipPort, RuleGossip)
		b.WriteString("\t}\n")
	}

	b.WriteString("\tchain in {\n\t\ttype filter hook prerouting priority -200; policy accept;\n")
	fmt.Fprintf(&b, "\t\tiifname %q jump %s\n", r.MeshPort, chainFromMesh)
	if len(r.ClientPorts) > 0 {
		fmt.Fprintf(&b, "\t\tiifname { %s } jump %s\n", quoteList(r.ClientPorts), chainFromClient)
	}
	b.WriteString("\t}\n")
	b.WriteString("\tchain out {\n\t\ttype filter hook postrouting priority 300; policy accept;\n")
	fmt.Fprintf(&b, "\t\toifname %q jump %s\n", r.MeshPort, chainToMesh)
	if r.GossipPort != 0 && len(r.ClientPorts) > 0 {
		fmt.Fprintf(&b, "\t\toifname { %s } jump %s\n", quoteList(r.ClientPorts), chainToClient)
	}
	b.WriteString("\t}\n")
	b.WriteString("}\n")
	return b.String()
}

func quoteList(names []string) string {
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = fmt.Sprintf("%q", n)
	}
	return strings.Join(q, ", ")
}

// Apply runs the script through nft -f. Nothing changes if any line fails.
func Apply(ctx context.Context, nftPath, script string) error {
	cmd := exec.CommandContext(ctx, nftPath, "-f", "-")
	cmd.Stdin = strings.NewReader(script)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("nft -f: %v: %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

// Exists reports whether the table is present.
func Exists(ctx context.Context, nftPath string) (bool, error) {
	cmd := exec.CommandContext(ctx, nftPath, "list", "table", "bridge", Table)
	out, err := cmd.CombinedOutput()
	if err == nil {
		return true, nil
	}
	if bytes.Contains(out, []byte("No such file or directory")) || bytes.Contains(out, []byte("does not exist")) {
		return false, nil
	}
	return false, fmt.Errorf("nft list table: %v: %s", err, strings.TrimSpace(string(out)))
}

// Delete removes the table if it exists.
func Delete(ctx context.Context, nftPath string) error {
	ok, err := Exists(ctx, nftPath)
	if err != nil || !ok {
		return err
	}
	out, err := exec.CommandContext(ctx, nftPath, "delete", "table", "bridge", Table).CombinedOutput()
	if err != nil {
		return fmt.Errorf("nft delete table: %v: %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

// Counters sums the drop counters of the table by rule comment, and
// returns the rule count.
func Counters(ctx context.Context, nftPath string) (map[string]uint64, int, error) {
	out, err := exec.CommandContext(ctx, nftPath, "-j", "list", "table", "bridge", Table).Output()
	if err != nil {
		return nil, 0, err
	}
	return parseCounters(out)
}

func parseCounters(js []byte) (map[string]uint64, int, error) {
	var doc struct {
		Nftables []struct {
			Rule *struct {
				Comment string            `json:"comment"`
				Expr    []json.RawMessage `json:"expr"`
			} `json:"rule"`
		} `json:"nftables"`
	}
	if err := json.Unmarshal(js, &doc); err != nil {
		return nil, 0, err
	}
	counts := map[string]uint64{}
	rules := 0
	for _, item := range doc.Nftables {
		if item.Rule == nil {
			continue
		}
		rules++
		for _, e := range item.Rule.Expr {
			var c struct {
				Counter *struct {
					Packets uint64 `json:"packets"`
				} `json:"counter"`
			}
			if json.Unmarshal(e, &c) == nil && c.Counter != nil {
				counts[item.Rule.Comment] += c.Counter.Packets
			}
		}
	}
	return counts, rules, nil
}

// RouteTable is the inet-family table for the gateway path (architecture
// §8.5): connection pinning marks for client traffic, and NAT out of the
// WAN while this node is a gateway.
const RouteTable = "trellis"

// MarkMask covers the connection mark bits that pin a connection to a
// gateway (0x7300 | node ID).
const MarkMask = 0xffff

// Routing is the content of the inet trellis table.
type Routing struct {
	AnycastIf string // anycast0: where this node's clients' traffic arrives
	// Mark is set on new client connections: it names the gateway they
	// are pinned to (0x7300 | node ID). 0: none selected, nothing marked.
	Mark   uint32
	NAT    bool   // this node is a gateway
	WAN    string // NAT out of this interface
	Prefix string // mesh prefix, the NAT source
	// UntrackSYN: the selected gateway is another node. Its replies reach
	// the client over layer 2 and never pass here, so conntrack sees only
	// the client's half of a TCP connection: after an untracked SYN, the
	// client's handshake ACK is picked up (nf_conntrack_tcp_loose) as an
	// established connection and gets the pin mark. A tracked SYN would
	// leave the entry in SYN_SENT and every later packet "invalid", with
	// no mark, following whichever gateway is selected now.
	UntrackSYN bool
}

// Render produces an nft script replacing the inet table atomically.
func (r Routing) Render() string {
	var b strings.Builder
	fmt.Fprintf(&b, "table inet %s\ndelete table inet %s\n", RouteTable, RouteTable)
	fmt.Fprintf(&b, "table inet %s {\n", RouteTable)
	b.WriteString("\t# Generated by trellis meshd. Changes are overwritten.\n")
	if r.UntrackSYN {
		b.WriteString("\tchain raw {\n\t\ttype filter hook prerouting priority raw; policy accept;\n")
		fmt.Fprintf(&b, "\t\tiifname %q tcp flags & (syn | ack) == syn notrack comment \"one-way TCP: pin from the handshake ACK\"\n", r.AnycastIf)
		b.WriteString("\t}\n")
	}
	b.WriteString("\tchain pre {\n\t\ttype filter hook prerouting priority mangle; policy accept;\n")
	if r.Mark != 0 {
		// Only while unpinned: a connection whose replies bypass this node
		// stays "new" in conntrack for its whole life, and re-marking it
		// would move it with every change of selection.
		fmt.Fprintf(&b, "\t\tiifname %q ct state new ct mark & %#x == 0 ct mark set ct mark | %#x comment \"pin new connections to the selected gateway\"\n",
			r.AnycastIf, MarkMask, r.Mark)
	}
	fmt.Fprintf(&b, "\t\tiifname %q meta mark set ct mark\n", r.AnycastIf)
	b.WriteString("\t}\n")
	if r.NAT && r.WAN != "" {
		b.WriteString("\tchain post {\n\t\ttype nat hook postrouting priority srcnat; policy accept;\n")
		fmt.Fprintf(&b, "\t\toifname %q ip saddr %s counter masquerade comment \"mesh clients out of the WAN\"\n", r.WAN, r.Prefix)
		b.WriteString("\t}\n")
	}
	b.WriteString("}\n")
	return b.String()
}

// DeleteTable removes a table of the given family if it exists.
func DeleteTable(ctx context.Context, nftPath, family, name string) error {
	out, err := exec.CommandContext(ctx, nftPath, "list", "table", family, name).CombinedOutput()
	if err != nil {
		if bytes.Contains(out, []byte("No such file or directory")) || bytes.Contains(out, []byte("does not exist")) {
			return nil
		}
		return fmt.Errorf("nft list table %s %s: %v: %s", family, name, err, strings.TrimSpace(string(out)))
	}
	if out, err := exec.CommandContext(ctx, nftPath, "delete", "table", family, name).CombinedOutput(); err != nil {
		return fmt.Errorf("nft delete table %s %s: %v: %s", family, name, err, strings.TrimSpace(string(out)))
	}
	return nil
}
