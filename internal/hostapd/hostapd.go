// Package hostapd renders hostapd configuration for the client access point
// (architecture §10) and chooses its channel.
package hostapd

import (
	"encoding/hex"
	"fmt"
	"strings"

	"meridian/trellis/internal/config"
	"meridian/trellis/internal/nl80211"
)

// Config is everything hostapd needs for one AP interface.
type Config struct {
	Interface  string
	Bridge     string
	CtrlDir    string
	SSID       string
	Passphrase string
	Country    string
	Band       string // 2g or 5g
	Channel    int
	HT         bool // 802.11n
	VHT        bool // 802.11ac (5 GHz only)
	MaxClients int  // 0 = hostapd's default
	// Isolate stops clients of this AP talking to each other directly.
	// Off: the client network is flat (architecture §7).
	Isolate bool
}

// Render produces the hostapd configuration file contents.
func Render(c Config) string {
	var b strings.Builder
	b.WriteString("# Generated by trellis meshd. Changes are overwritten.\n")
	fmt.Fprintf(&b, "interface=%s\n", c.Interface)
	if c.Bridge != "" {
		fmt.Fprintf(&b, "bridge=%s\n", c.Bridge)
	}
	b.WriteString("driver=nl80211\n")
	fmt.Fprintf(&b, "ctrl_interface=%s\n", c.CtrlDir)
	b.WriteString("ctrl_interface_group=0\n")
	// Hex form avoids every quoting question for the SSID.
	fmt.Fprintf(&b, "ssid2=%s\n", hex.EncodeToString([]byte(c.SSID)))
	b.WriteString("utf8_ssid=1\n")
	if c.Country != "" {
		fmt.Fprintf(&b, "country_code=%s\n", c.Country)
		b.WriteString("ieee80211d=1\n")
	}
	if c.Band == config.Band5G {
		b.WriteString("hw_mode=a\n")
	} else {
		b.WriteString("hw_mode=g\n")
	}
	fmt.Fprintf(&b, "channel=%d\n", c.Channel)
	if c.HT {
		b.WriteString("ieee80211n=1\n")
	}
	if c.VHT && c.Band == config.Band5G {
		b.WriteString("ieee80211ac=1\n")
		b.WriteString("vht_oper_chwidth=0\n")
	}
	b.WriteString("wmm_enabled=1\n")
	b.WriteString("beacon_int=100\n")
	b.WriteString("auth_algs=1\n")
	b.WriteString("wpa=2\n")
	b.WriteString("wpa_key_mgmt=WPA-PSK\n")
	b.WriteString("rsn_pairwise=CCMP\n")
	fmt.Fprintf(&b, "wpa_passphrase=%s\n", c.Passphrase)
	// Management frame protection optional: phones that support it use it,
	// older devices still join.
	b.WriteString("ieee80211w=1\n")
	// Multicast as unicast: phones reliably receive ATAK's multicast
	// (architecture §9).
	b.WriteString("multicast_to_unicast=1\n")
	b.WriteString("disassoc_low_ack=1\n")
	if c.Isolate {
		b.WriteString("ap_isolate=1\n")
	} else {
		b.WriteString("ap_isolate=0\n")
	}
	if c.MaxClients > 0 {
		fmt.Fprintf(&b, "max_num_sta=%d\n", c.MaxClients)
	}
	return b.String()
}

// Preferred channels per band, in order. 5 GHz stays in UNII-1 and UNII-3
// (no radar detection needed); 2.4 GHz uses the three non-overlapping
// channels.
var preferred = map[string][]int{
	config.Band5G: {36, 40, 44, 48, 149, 153, 157, 161},
	config.Band2G: {1, 6, 11},
}

// Choice is the selected AP channel.
type Choice struct {
	Band    string
	Channel int
	FreqMHz int
}

// Choose picks the AP channel. pinned, when non-zero, is the operator's
// choice and only has to be usable. Otherwise the first preferred channel
// the radio can start an AP on wins, preferring distance from avoidMHz
// (the mesh frequency) when both are in the same band.
func Choose(band string, bi *nl80211.BandInfo, pinned int, avoidMHz int) (Choice, error) {
	usable := func(ch int) (int, bool) {
		f, err := config.ChannelFrequencyMHz(band, ch)
		if err != nil || bi == nil {
			return 0, false
		}
		for _, fr := range bi.Frequencies {
			if int(fr.MHz) == f {
				return f, !fr.Disabled && !fr.NoIR && !fr.Radar
			}
		}
		return 0, false
	}
	if pinned != 0 {
		f, ok := usable(pinned)
		if !ok {
			return Choice{}, fmt.Errorf("channel %d is not usable for an AP on this radio in the current regulatory domain", pinned)
		}
		return Choice{Band: band, Channel: pinned, FreqMHz: f}, nil
	}
	best := Choice{}
	bestDist := -1
	for _, ch := range preferred[band] {
		f, ok := usable(ch)
		if !ok {
			continue
		}
		dist := f - avoidMHz
		if dist < 0 {
			dist = -dist
		}
		if avoidMHz == 0 {
			// First usable preferred channel.
			return Choice{Band: band, Channel: ch, FreqMHz: f}, nil
		}
		if dist > bestDist {
			best, bestDist = Choice{Band: band, Channel: ch, FreqMHz: f}, dist
		}
	}
	if bestDist < 0 {
		return Choice{}, fmt.Errorf("no usable %s channel for an AP on this radio (all disabled, passive-only or radar)", band)
	}
	return best, nil
}

// WiFiQR is the string Android and iOS cameras recognise as Wi-Fi
// credentials.
func WiFiQR(ssid, passphrase string) string {
	esc := func(s string) string {
		r := strings.NewReplacer(`\`, `\\`, `;`, `\;`, `,`, `\,`, `:`, `\:`, `"`, `\"`)
		return r.Replace(s)
	}
	return "WIFI:T:WPA;S:" + esc(ssid) + ";P:" + esc(passphrase) + ";;"
}
