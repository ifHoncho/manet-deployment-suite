#!/usr/bin/env python3
"""Generate Go constants from C enums in a Linux UAPI header.

Usage: genconst.py --header /usr/include/linux/nl80211.h --package nl80211 \
           [--enum nl80211_commands --enum nl80211_attrs ...] > consts_gen.go

With no --enum, every enum in the header is emitted. Values are emitted as
untyped Go constants so they can be used wherever a netlink attribute type or
command id is needed without casts. Names are kept verbatim so they can be
grepped against the kernel source and documentation.
"""
import argparse
import re
import sys


def strip_comments(src: str) -> str:
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    return src


def parse_enums(src: str):
    """Yield (enum_name, [(name, value_or_None), ...]) for each enum."""
    src = strip_comments(src)
    # Drop preprocessor lines; they can appear inside enum bodies.
    src = "\n".join(l for l in src.splitlines() if not l.lstrip().startswith("#"))
    for m in re.finditer(r"enum\s+(\w+)\s*\{(.*?)\}\s*;", src, flags=re.S):
        name, body = m.group(1), m.group(2)
        entries = []
        for raw in body.split(","):
            raw = raw.strip()
            if not raw:
                continue
            if "=" in raw:
                ident, val = (s.strip() for s in raw.split("=", 1))
            else:
                ident, val = raw, None
            if not re.fullmatch(r"[A-Za-z_]\w*", ident):
                raise SystemExit(f"cannot parse enum entry {raw!r} in {name}")
            entries.append((ident, val))
        yield name, entries


def c_expr_to_go(expr: str) -> str:
    # C expressions used in these headers are a subset Go accepts verbatim:
    # integers, hex, parentheses, <<, -, +, |, and identifiers.
    # Drop C integer-literal suffixes (1U, 0x10UL, 7ULL): Go constants are untyped.
    expr = re.sub(r"\b(0[xX][0-9A-Fa-f]+|\d+)[uU]?[lL]{0,2}\b", lambda m: m.group(1), expr)
    if not re.fullmatch(r"[\w\s()<>|+\-]+", expr):
        raise SystemExit(f"unsupported C expression {expr!r}")
    return expr


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--header", required=True)
    ap.add_argument("--package", required=True)
    ap.add_argument("--enum", action="append", default=[])
    args = ap.parse_args()

    with open(args.header) as f:
        src = f.read()

    out = [
        f"// Code generated by tools/genconst/genconst.py from {args.header}; DO NOT EDIT.",
        "",
        f"package {args.package}",
        "",
    ]
    wanted = set(args.enum)
    seen = set()
    for name, entries in parse_enums(src):
        if wanted and name not in wanted:
            continue
        seen.add(name)
        out.append(f"// enum {name}")
        out.append("const (")
        prev = None
        for ident, val in entries:
            if val is None:
                if prev is None:
                    go = "0"
                else:
                    go = f"{prev} + 1"
            else:
                go = c_expr_to_go(val)
            out.append(f"\t{ident} = {go}")
            prev = ident
        out.append(")")
        out.append("")
    missing = wanted - seen
    if missing:
        raise SystemExit(f"enums not found in header: {sorted(missing)}")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
